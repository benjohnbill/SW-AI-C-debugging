const int qs2[] = {64, 34, 25, 12, 22, 11, 90};
const int qs3[] = {3, 1, 4, 1, 5, 9, 2, 6, 5, 3, 5};   /* 중복 원소 */
const int qs4[] = {1, 2, 3, 4, 5};                     /* 이미 정렬됨 — 최악의 경우 */

#endif
